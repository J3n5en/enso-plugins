// 把原作 ES Modules 收成侧栏能跑的普通脚本。
// 宿主会把 <script src> 内联成不带 type="module" 的脚本，并且不解析 import。
// 每个模块仍包在自己的函数里，避免 clamp / TAU 等同名绑定撞在一起。
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const files = ['data.js', 'airframes.js', 'engine.js', 'audio.js', 'render.js', 'app.js'];
const source = files.map(name => readFileSync(join(root, name), 'utf8')).join('\n');
const stamp = createHash('sha256').update(source).digest('hex');

function strip(code) {
  return code
    .replace(/^\s*import\s.+?;\s*$/gm, '')
    .replace(/^\s*export\s+\{[^}]*\};\s*$/gm, '')
    .replace(/^export\s+/gm, '');
}

function wrap(name, code, prelude = '', postlude = '') {
  return `/* ${name} */\n(() => {\n${prelude}${strip(code).trim()}\n${postlude}\n})();\n`;
}

const parts = [
  wrap(
    'data.js',
    readFileSync(join(root, 'data.js'), 'utf8'),
    '',
    'TF.WIDTH=WIDTH;TF.HEIGHT=HEIGHT;TF.STAGE_SECONDS=STAGE_SECONDS;TF.BOSS_AT=BOSS_AT;TF.DROP_TTL=DROP_TTL;TF.SHIPS=SHIPS;TF.WEAPONS=WEAPONS;TF.STAGES=STAGES;TF.UPGRADES=UPGRADES;',
  ),
  wrap('airframes.js', readFileSync(join(root, 'airframes.js'), 'utf8'), '', 'TF.drawAirframe=drawAirframe;'),
  wrap(
    'engine.js',
    readFileSync(join(root, 'engine.js'), 'utf8'),
    'const { WIDTH, HEIGHT, SHIPS, WEAPONS, STAGES, UPGRADES, STAGE_SECONDS, BOSS_AT, DROP_TTL } = TF;\n',
    'TF.clamp=clamp;TF.segmentDistance=segmentDistance;TF.seededRandom=seededRandom;TF.chooseWeapon=chooseWeapon;TF.Game=Game;',
  ),
  wrap('audio.js', readFileSync(join(root, 'audio.js'), 'utf8'), '', 'TF.Sound=Sound;'),
  wrap(
    'render.js',
    readFileSync(join(root, 'render.js'), 'utf8'),
    'const drawShip = TF.drawAirframe;\n',
    'TF.drawFrame=drawFrame;',
  ),
  wrap(
    'app.js',
    readFileSync(join(root, 'app.js'), 'utf8'),
    'const { Game, clamp, WIDTH, HEIGHT, SHIPS, WEAPONS, STAGES, STAGE_SECONDS, DROP_TTL, drawFrame, Sound } = TF;\n',
  ),
];

const boot = `'use strict';
// Generated by assemble.mjs from the Thunderfall modules. Do not edit by hand.
// source-sha256: ${stamp}
const TF = globalThis.TF = {};
${parts.join('\n')}
`;
writeFileSync(join(root, 'boot.js'), boot);
process.stdout.write(`boot.js ${Buffer.byteLength(boot)} bytes ${stamp}\n`);
